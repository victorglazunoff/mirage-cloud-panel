#!/usr/bin/env node
/**
 * Regenerates the favicon, the logo PNGs and the PWA / home-screen icons from the
 * Mirage Cloud Panel mark in `docs/logo/`. Run after changing the mark:
 *
 *   node scripts/generate-brand-icons.mjs
 *
 * Sources:
 *   docs/logo/mirage-logo-round.svg              mark on a dark disc (favicon, logos)
 *   docs/logo/mirage-logo-round-transparent.svg  bare mark (placed on the square app icon)
 */
import { copyFile, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = path.join(root, 'public');
const roundSvgPath = path.join(root, 'docs', 'logo', 'mirage-logo-round.svg');
const bareSvgPath = path.join(root, 'docs', 'logo', 'mirage-logo-round-transparent.svg');

/** Panel background («Кабина» ink), also the manifest's background and theme colour. */
const BACKGROUND = '#12110F';
/**
 * Share of the square app icon the mark's box takes. The maskable safe zone is a
 * centred circle 80% wide; at 0.76 the ring stays well inside it on every launcher.
 */
const APP_ICON_MARK_SCALE = 0.76;
const LOGO_SIZES = [32, 64, 128, 256, 512];
const APP_ICON_SIZES = [72, 96, 128, 144, 152, 192, 384, 512];

/** Square, full-bleed app icon: the bare mark centred on the panel background. */
function buildAppIconSvg(bareSvg) {
  const inner = bareSvg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .trim();
  const offset = (26 * (1 - APP_ICON_MARK_SCALE)) / 2;
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 26 26" width="512" height="512" fill="none">',
    '  <!-- Mirage Cloud Panel app icon (generated by scripts/generate-brand-icons.mjs) -->',
    `  <rect width="26" height="26" fill="${BACKGROUND}"/>`,
    `  <g transform="translate(${offset.toFixed(3)} ${offset.toFixed(3)}) scale(${APP_ICON_MARK_SCALE})">`,
    `    ${inner.split('\n').map((line) => line.trim()).join('\n    ')}`,
    '  </g>',
    '</svg>',
    '',
  ].join('\n');
}

async function renderPng(svg, size, outputPath) {
  // Both sources declare a 512–1024 px canvas, so they rasterise at least that large and only scale down.
  await sharp(Buffer.from(svg))
    .resize(size, size)
    .png({ compressionLevel: 9 })
    .toFile(outputPath);
}

const roundSvg = await readFile(roundSvgPath, 'utf8');
const bareSvg = await readFile(bareSvgPath, 'utf8');
const appIconSvg = buildAppIconSvg(bareSvg);

await copyFile(roundSvgPath, path.join(publicDir, 'favicon.svg'));
await copyFile(bareSvgPath, path.join(publicDir, 'logo.svg'));
await writeFile(path.join(publicDir, 'icons', 'icon-maskable.svg'), appIconSvg);
await renderPng(roundSvg, 64, path.join(publicDir, 'favicon.png'));
for (const size of LOGO_SIZES) {
  await renderPng(roundSvg, size, path.join(publicDir, `logo-${size}.png`));
}
for (const size of APP_ICON_SIZES) {
  await renderPng(appIconSvg, size, path.join(publicDir, 'icons', `icon-${size}x${size}.png`));
}
console.log('Brand icons written to public/.');
